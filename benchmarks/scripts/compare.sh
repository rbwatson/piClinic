#!/usr/bin/env bash
# benchmarks/scripts/compare.sh
# Compare two benchmark raw.json result files side by side.
#
# Usage:
#   ./compare.sh <raw1.json> <raw2.json> [output.md]
#
# If output.md is omitted or "-", report is written to stdout.
#
# Column headings for response time:
#   Different versions (v1 vs v2): "V1 response (ms)" / "V2 response (ms)"
#   Same version:                  "V1-1 response (ms)" / "V1-2 response (ms)"

set -euo pipefail

if [[ $# -lt 2 ]]; then
  echo "Usage: $0 <raw1.json> <raw2.json> [output.md]" >&2
  exit 1
fi

FILE1="$1"
FILE2="$2"
OUTPUT_FILE="${3:--}"

for f in "${FILE1}" "${FILE2}"; do
  if [[ ! -f "${f}" ]]; then
    echo "ERROR: file not found: ${f}" >&2
    exit 1
  fi
done

if ! command -v jq &>/dev/null; then
  echo "ERROR: 'jq' is required but not found on PATH" >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# Extract run metadata
# ---------------------------------------------------------------------------
TS1="$(jq -r '.run.timestamp'       "${FILE1}")"
LABEL1="$(jq -r '.run.target_label' "${FILE1}")"
URL1="$(jq -r '.run.target_url'     "${FILE1}")"
VER1="$(jq -r '.run.version'        "${FILE1}")"
SCORE_NORMAL1="$(jq -r '.scores.composite_normal' "${FILE1}")"
SCORE_STRESS1="$(jq -r '.scores.composite_stress'  "${FILE1}")"

TS2="$(jq -r '.run.timestamp'       "${FILE2}")"
LABEL2="$(jq -r '.run.target_label' "${FILE2}")"
URL2="$(jq -r '.run.target_url'     "${FILE2}")"
VER2="$(jq -r '.run.version'        "${FILE2}")"
SCORE_NORMAL2="$(jq -r '.scores.composite_normal' "${FILE2}")"
SCORE_STRESS2="$(jq -r '.scores.composite_stress'  "${FILE2}")"

# ---------------------------------------------------------------------------
# Determine response time column headings
# tr used instead of ${^^} for bash 3 compatibility (macOS default shell)
# ---------------------------------------------------------------------------
VER1_UP="$(echo "${VER1}" | tr '[:lower:]' '[:upper:]')"
VER2_UP="$(echo "${VER2}" | tr '[:lower:]' '[:upper:]')"

if [[ "${VER1}" != "${VER2}" ]]; then
  COL1="${VER1_UP} response (ms)"
  COL2="${VER2_UP} response (ms)"
else
  COL1="${VER1_UP}-1 response (ms)"
  COL2="${VER2_UP}-2 response (ms)"
fi

# ---------------------------------------------------------------------------
# Build Suite A comparison table (joined on resource + method + variant)
# Tests missing from file 2 show "N/A" in the second column.
# ---------------------------------------------------------------------------
SUITE_A_TABLE="$(jq -r --slurpfile f2 "${FILE2}" '
  .tests[] as $t1 |
  ( [ $f2[0].tests[]
      | select(.resource == $t1.resource
           and .method   == $t1.method
           and .variant  == $t1.variant)
    ] | first // null
  ) as $t2 |
  "| \($t1.resource) | \($t1.method) | \($t1.variant) | \($t1.response_time_ms) | \(if $t2 then $t2.response_time_ms else "N/A" end) | \($t1.frequency_normal) | \($t1.frequency_stress) |"
' "${FILE1}")"

# ---------------------------------------------------------------------------
# Build Suite B comparison table (joined on id)
# ---------------------------------------------------------------------------
SUITE_B_TABLE="$(jq -r --slurpfile f2 "${FILE2}" '
  .suite_b[] as $t1 |
  ( [ $f2[0].suite_b[]
      | select(.id == $t1.id)
    ] | first // null
  ) as $t2 |
  "| \($t1.id) | \($t1.variant) | \($t1.response_time_ms) | \(if $t2 then $t2.response_time_ms else "N/A" end) |"
' "${FILE1}")"

# ---------------------------------------------------------------------------
# Build report
# ---------------------------------------------------------------------------
build_report() {
cat <<EOF
# piClinic Benchmark Comparison

## File 1: ${LABEL1}

| Field | Value |
|---|---|
| Target | ${LABEL1} |
| URL | ${URL1} |
| Version | ${VER1} |
| Timestamp | ${TS1} |

## File 2: ${LABEL2}

| Field | Value |
|---|---|
| Target | ${LABEL2} |
| URL | ${URL2} |
| Version | ${VER2} |
| Timestamp | ${TS2} |

## Composite Scores

| Profile | ${COL1} | ${COL2} |
|---|---|---|
| Normal (45-week typical) | ${SCORE_NORMAL1} | ${SCORE_NORMAL2} |
| Stress (5-week event)    | ${SCORE_STRESS1} | ${SCORE_STRESS2} |

Composite score = frequency-weighted mean response time.
Frequency tiers: rare=0.2, low=1, med=10, high=100.

## Suite A Results

| Resource | Method | Variant | ${COL1} | ${COL2} | Freq (normal) | Freq (stress) |
|---|---|---|---|---|---|---|
${SUITE_A_TABLE}

## Suite B Results (Infrastructure)

| Test | Variant | ${COL1} | ${COL2} |
|---|---|---|---|
${SUITE_B_TABLE}

---
*Generated by benchmarks/scripts/compare.sh*
EOF
}

# ---------------------------------------------------------------------------
# Write output
# ---------------------------------------------------------------------------
if [[ "${OUTPUT_FILE}" == "-" ]]; then
  build_report
else
  build_report > "${OUTPUT_FILE}"
  echo "Comparison written to: ${OUTPUT_FILE}" >&2
fi
