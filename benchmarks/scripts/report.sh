#!/usr/bin/env bash
# benchmarks/scripts/report.sh
# Generate a Markdown summary report from a benchmark raw.json results file.
#
# Usage:
#   ./report.sh <raw.json> [output.md]
#
# If output.md is omitted, report is written to stdout.
# If output.md is "-", report is written to stdout.

set -euo pipefail

if [[ $# -lt 1 ]]; then
  echo "Usage: $0 <raw.json> [output.md]" >&2
  exit 1
fi

RAW_JSON="$1"
OUTPUT_FILE="${2:--}"

if [[ ! -f "${RAW_JSON}" ]]; then
  echo "ERROR: file not found: ${RAW_JSON}" >&2
  exit 1
fi

if ! command -v jq &>/dev/null; then
  echo "ERROR: 'jq' is required but not found on PATH" >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# Extract run metadata
# ---------------------------------------------------------------------------
TS="$(jq -r '.run.timestamp'    "${RAW_JSON}")"
LABEL="$(jq -r '.run.target_label' "${RAW_JSON}")"
URL="$(jq -r '.run.target_url'  "${RAW_JSON}")"
VER="$(jq -r '.run.version'     "${RAW_JSON}")"
SCORE_NORMAL="$(jq -r '.scores.composite_normal' "${RAW_JSON}")"
SCORE_STRESS="$(jq -r '.scores.composite_stress'  "${RAW_JSON}")"

# ---------------------------------------------------------------------------
# Build report string
# ---------------------------------------------------------------------------
build_report() {
cat <<EOF
# piClinic Benchmark Report

## Run Summary

| Field | Value |
|---|---|
| Target | ${LABEL} |
| URL | ${URL} |
| Version | ${VER} |
| Timestamp | ${TS} |

## Composite Scores

| Profile | Score (ms) | Lower is better |
|---|---|---|
| Normal (45-week typical) | ${SCORE_NORMAL} | |
| Stress (5-week event)    | ${SCORE_STRESS} | |

Composite score = frequency-weighted mean response time.
Frequency tiers: rare=0.2, low=1, med=10, high=100.

## Suite A Results

| Resource | Method | Variant | Response (ms) | Freq (normal) | Freq (stress) |
|---|---|---|---|---|---|
$(jq -r '.tests[] | "| \(.resource) | \(.method) | \(.variant) | \(.response_time_ms) | \(.frequency_normal) | \(.frequency_stress) |"' "${RAW_JSON}")

## Suite B Results (Infrastructure)

| Test | Variant | Response (ms) |
|---|---|---|
$(jq -r '.suite_b[] | "| \(.id) | \(.variant) | \(.response_time_ms) |"' "${RAW_JSON}")

---
*Generated by benchmarks/scripts/report.sh*
EOF
}

# ---------------------------------------------------------------------------
# Write output
# ---------------------------------------------------------------------------
if [[ "${OUTPUT_FILE}" == "-" ]]; then
  build_report
else
  build_report > "${OUTPUT_FILE}"
  echo "Report written to: ${OUTPUT_FILE}" >&2
fi
